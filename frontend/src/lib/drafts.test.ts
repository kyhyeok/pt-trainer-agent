		'트레이너 확인 필요: 사흘째 저녁을 굶었다고 하고 먹은 게 거의 없어요.',
		'트레이너 확인 필요: 없던 구토 증상이 식후에 생겼다고 함',
		'트레이너 확인: 필요 — 먹고 토하기 언급',
