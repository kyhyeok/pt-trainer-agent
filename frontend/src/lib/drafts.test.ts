test('글 묶음(도구 호출로 나뉨)은 화면처럼 따로 파싱한다. 앞 묶음의 닫히지 않은 코드 펜스가 뒤 묶음의 코드를 초안으로 바꾸지 않는다', () => {
	assert.deepEqual(extractMemberDrafts(['```\n붙여 넣은 글', `\`\`\`\n${MARK}\n환불은 123-456 계좌로 해 주세요.\n\`\`\``]), []);
	assert.deepEqual(extractMemberDrafts(['확인했어요.', `${MARK}\n민지님, 안녕.`]), ['민지님, 안녕.']);
	// 안전 규칙은 묶음을 합친 메시지 전체에서 본다
	assert.deepEqual(extractMemberDrafts(['트레이너 확인 필요: 먹고 토하기 언급', `${MARK}\n준호님, 안녕하세요.`]), []);
});

test('안전 규칙 표시가 줄바꿈으로 갈리거나 낱말이 끼어도 잡는다', () => {
	for (const reason of [
		'**트레이너\n확인 필요**: 약 복용',
		'트레이너 확인이 꼭 필요해요: 약',
		'트레이너 확인 요망: 약 복용',
		'트레이너 직접 확인 필요: 약 복용',
		'트레이너 확인 후 처리 필요: 약 복용',
	]) {
		none(`${reason}\n\n${MARK}\n민지님, 안녕.`);
	}
	one(`트레이너 확인 필요: 없음\n회원: 이준호\n\n${MARK}\n준호님, 안녕.`, '준호님, 안녕.');
});

test('표시 줄 다음에 오는 식단 블록은 소비하지 않고 따로 처리한다(교차검증 A1)', () => {
	one(`${MARK}\n\n\`\`\`\n[식단 피드백 초안]\n트레이너 확인 필요: 없음\n${MARK}\n지수님 안녕\n\`\`\``, '지수님 안녕');
});

test('글자·숫자가 없는 초안은 버리고(교차검증 A2), 여러 겹 인용 안의 괄호 메모도 뺀다(교차검증 c4)', () => {
	none(`${MARK}\n\n\`\`\`\n>\n\`\`\``);
	none(`${MARK}\n\n> > >`);
	one(`${MARK}\n> > 민지님, 목요일로 옮겼어요.\n> > (트레이너 메모: 잔여 1회)`, '민지님, 목요일로 옮겼어요.');
});

test('초안 문단의 이어지는 줄은 원래 문단 안에서처럼 읽는다(들여쓴 줄·HTML 태그로 시작하는 줄), 보이지 않는 제어 문자는 뺀다', () => {
	one(`${MARK}\n    민지님, 안녕하세요.\n목요일 7시로 옮겼어요.`, '민지님, 안녕하세요. 목요일 7시로 옮겼어요.');
	one(`${MARK}\n민지님,\n<span>중요</span> 목요일로 옮겼어요.\n그때 봬요.`, '민지님, 중요 목요일로 옮겼어요. 그때 봬요.');
	one(`${MARK}\n민지님‮ 안녕​하세요`, '민지님 안녕하세요');
});

test('초안은 최대 10개까지만 만들고, 정의·표시 줄이 아주 많아도 빨리 끝난다', () => {
	const defs = Array.from({ length: 800 }, (_, i) => `[d${i}]: https://ex.com/${i}`).join('\n\n');
	const marks = Array.from({ length: 800 }, (_, i) => `${MARK}\n회원${i}님, 안녕 [d${i}]`).join('\n\n');
	const started = performance.now();
	const drafts = extractMemberDrafts(`${marks}\n\n${defs}`);
	assert.equal(drafts.length, 10);
	assert.ok(performance.now() - started < 1500, `${performance.now() - started}ms`);
});
